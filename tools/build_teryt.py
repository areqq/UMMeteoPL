#!/usr/bin/env python3
"""Rebuild teryt.tsv: meteo.pl location id -> 4-digit county (powiat) TERYT code.

IMGW weather warnings (danepubliczne.imgw.pl/api/data/warningsmeteo) list the
counties they apply to by TERYT code. County codes and names come from the
official PRG register (GUGiK WFS); the county of each location is taken from
the 'pow.<name>' part of its woj/* entry, or the town itself for cities with
county rights ('powiat Kraków').

    python3 tools/build_teryt.py   (from the plugin directory, needs network)
"""
import os
import re
import sys
from urllib.request import urlopen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(ROOT))
storage = __import__(os.path.basename(ROOT) + ".storage", fromlist=["x"])

WFS = ("https://mapy.geoportal.gov.pl/wss/service/PZGIK/PRG/WFS/AdministrativeBoundaries"
       "?SERVICE=WFS&VERSION=2.0.0&REQUEST=GetFeature&TYPENAMES=ms:{layer}"
       "&PROPERTYNAME=ms:JPT_KOD_JE,ms:JPT_NAZWA_")
ROW = re.compile(r"<ms:JPT_KOD_JE>(\d+)</ms:JPT_KOD_JE>\s*<ms:JPT_NAZWA_>([^<]*)</ms:JPT_NAZWA_>")

# Ids no longer in woj/* that may still sit in users' favourites.
# 1018: 'Jelenia Góra, pow.jeleniogórski' - same grid cell as 981 (x=158, y=441).
EXTRA = {"1018": "0261"}


def units(layer):
    with urlopen(WFS.format(layer=layer), timeout=300) as r:
        return set(ROW.findall(r.read().decode("utf-8")))


def main():
    voivodeships = {name: code for code, name in units("A01_Granice_wojewodztw")}
    counties = {(code[:2], name.lower()): code for code, name in units("A02_Granice_powiatow")}
    table, missing = dict(EXTRA), []
    for label, woj_file in storage.VOIVODESHIPS:
        for loc in storage.towns(woj_file):
            parts = [p.strip() for p in loc.name.split(",")]
            county = parts[1][4:] if len(parts) > 1 and parts[1].startswith("pow.") else parts[0]
            code = counties.get((voivodeships[label], f"powiat {county}".lower()))
            if code:
                table[loc.id] = code
            else:
                missing.append(f"{woj_file}: {loc}")
    if missing:
        sys.exit("no county for:\n" + "\n".join(missing))
    with open(os.path.join(ROOT, "teryt.tsv"), "w", encoding="utf-8") as f:
        f.write("# meteo.pl id -> county TERYT (PRG, GUGiK); generated by tools/build_teryt.py\n")
        f.writelines(f"{i}\t{table[i]}\n" for i in sorted(table, key=int))
    print(f"{len(table)} locations, {len(set(table.values()))} counties")


if __name__ == "__main__":
    main()
